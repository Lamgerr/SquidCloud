const helpers = `const resolveIcon = (base: string) =>
  (Fluent as any)[base + 'Filled'] || (Fluent as any)[base + 'Regular'] || (Fluent as any).CircleFilled;

const wrapIcon = (base: string) => {
  const C = resolveIcon(base);
  return ({ size = 24, color, className = '', ...rest }: { size?: number; color?: string; className?: string; weight?: string }) => (
    <C size={size} color={color} className={\`sc-icon \${className}\`} {...rest} />
  );
};
`;

const pBlock =
  'const P = {\n' +
  Object.entries(map)
    .map(([k, v]) => `  ${k}: wrapIcon('${v}'),`)
    .join('\n') +
  '\n};\n\nexport { P };\n';

const start = src.indexOf('const fallbackFor');
const endMarker = 'export { P };';
const end = src.indexOf(endMarker) + endMarker.length;

if (start === -1 || end === -1) {
  console.error('ANCHORS NOT FOUND');
  process.exit(1);
}

src = src.slice(0, start) + helpers + '\n' + pBlock + src.slice(end);

src = src.replace("import * as MC from '@mingcute/react';", "import * as Fluent from '@fluentui/react-icons';");

