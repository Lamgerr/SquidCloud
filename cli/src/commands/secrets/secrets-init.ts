import { existsSync, writeFileSync } from 'node:fs'
import { basename } from 'node:path'
import { createInterface } from 'node:readline'
import { randomUUID } from 'node:crypto'
import { apiClient } from '../../lib/api/client.js'
import { logger } from '../../lib/output/logger.js'

function generateProjectId(): string {
  return randomUUID().replace(/-/g, '').slice(0, 16)
}

async function confirm(prompt: string): Promise<boolean> {
  const rl = createInterface({ input: process.stdin, output: process.stdout })
  return new Promise(resolve => {
    rl.question(`${prompt} (Y/n) `, answer => {
      rl.close()
      if (answer.trim() === '') return resolve(true)
      resolve(answer.toLowerCase() === 'y' || answer.toLowerCase() === 'yes')
    })
  })
}

function writeSquidproxy(projectName: string): void {
  const content = `# SquidVeil secrets proxy configuration
# Generated by squidcloud secrets init

[squidproxy]
version = "1.0"
project = "${projectName}"

# Add your secret references below:
# [[secrets]]
# name = "MY_API_KEY"
# type = "env"
`
  writeFileSync('.squidproxy', content, 'utf-8')
}

function writeSquidveil(projectName: string, projectId: string): void {
  const content = JSON.stringify(
    {
      project_id: projectId,
      project_name: projectName,
      version: 1,
      created_at: new Date().toISOString(),
    },
    null,
    2,
  )
  writeFileSync('.squidveil', content, 'utf-8')
}

export default async function secretsInit(): Promise<void> {
  const projectName = basename(process.cwd())
  const projectId = generateProjectId()

  const existingFiles: string[] = []
  if (existsSync('.squidproxy')) existingFiles.push('.squidproxy')
  if (existsSync('.squidveil')) existingFiles.push('.squidveil')

  if (existingFiles.length > 0) {
    logger.warn(`Existing files will be overwritten: ${existingFiles.join(', ')}`)
    const ok = await confirm('Continue?')
    if (!ok) {
      logger.info('Initialisation cancelled')
      return
    }
  }

  writeSquidproxy(projectName)
  writeSquidveil(projectName, projectId)

  logger.success('SquidVeil project initialised')
  logger.log('')
  logger.log('  Files created:')
  logger.log('    .squidproxy  - Secret reference definitions')
  logger.log('    .squidveil   - Project metadata')
  logger.log('')
  logger.log('  Next steps:')
  logger.log(`    1. Edit .squidproxy to add your secret references`)
  logger.log(`    2. Run \`squidcloud secrets list\` to see available secrets`)
  logger.log(`    3. Use \`squidcloud secrets export --output .squidproxy\``)
  logger.log(`       to generate .squidproxy from existing secrets`)
  logger.log('')
}
