import { getComponent } from './component-registry';
import { ALL_VARIABLES } from './variable-registry';

export interface VisualStep {
  id: string;
  componentId: string;
  label: string;
  config: Record<string, unknown>;
  subTypes: string[];
}

export function yamlFromSteps(steps: VisualStep[], pipelineName?: string, pipelineDescription?: string): string {
  if (steps.length === 0) return '# Drag components from the palette to build your pipeline\n';

  const lines: string[] = [];
  lines.push(`# Auto-generated by SquidActions Visual Editor`);
  lines.push(`# ${steps.length} step(s) · ${ALL_VARIABLES.length} available variables`);
  if (pipelineName) lines.push(`name: ${pipelineName}`);
  if (pipelineDescription) lines.push(`description: '${pipelineDescription}'`);
  lines.push(`on:`);
  lines.push(`  manual: true`);
  lines.push(``);
  lines.push(`jobs:`);

  let jobIndex = 0;
  let currentJob = '';

  for (let i = 0; i < steps.length; i++) {
    const step = steps[i];
    const comp = getComponent(step.componentId);
    if (!comp) continue;

    if (comp.category === 'triggers') {
      if (i === 0) {
        // First trigger becomes the pipeline trigger config
        lines.push(`  ${step.componentId}:`);
        Object.entries(step.config).forEach(([k, v]) => {
          lines.push(`    ${k}: ${formatYamlValue(v)}`);
        });
        lines.push(``);
      }
      continue;
    }

    if (i === 0 || steps[i-1]?.componentId === 'trigger') {
      jobIndex++;
      currentJob = `job-${jobIndex}`;
      lines.push(`  ${currentJob}:`);
      lines.push(`    name: "${comp.category} step"`);
      lines.push(`    steps:`);
    }

    const stepName = step.label || comp.name;
    lines.push(`      - name: "${stepName}"`);
    
    // Map component IDs to action refs
    const actionMap: Record<string, string> = {
      'echo': 'squidcloud/echo',
      'transform': 'squidcloud/transform',
      'http-request': 'squidcloud/http',
      'webhook-send': 'squidcloud/webhook',
      'file-copy': 'squidcloud/file-copy',
      'file-move': 'squidcloud/file-move',
      'file-delete': 'squidcloud/file-delete',
      'file-rename': 'squidcloud/file-rename',
      'file-upload': 'squidcloud/file-upload',
      'file-download': 'squidcloud/file-download',
      'file-compress': 'squidcloud/compress',
      'file-extract': 'squidcloud/extract',
      'file-sync': 'squidcloud/sync',
      'file-scan': 'squidcloud/scan',
      'slack-message': 'squidcloud/slack',
      'discord-message': 'squidcloud/discord',
      'email-send': 'squidcloud/email',
      'condition': 'squidcloud/condition',
      'for-loop': 'squidcloud/for-each',
      'delay': 'squidcloud/delay',
      'try-catch': 'squidcloud/try-catch',
      'template': 'squidcloud/template',
      'log-message': 'squidcloud/log',
      'push-notification': 'squidcloud/push',
      'custom-script': 'squidcloud/script',
    };

    lines.push(`        action: ${actionMap[step.componentId] || `squidcloud/${step.componentId}`}`);
    
    const configEntries = Object.entries(step.config).filter(([, v]) => v !== undefined && v !== '');
    if (configEntries.length > 0 || step.subTypes.length > 0) {
      lines.push(`        with:`);
      configEntries.forEach(([k, v]) => {
        if (v === '' || v === undefined) return;
        lines.push(`          ${k}: ${formatYamlValue(v)}`);
      });
    }
    lines.push(``);
  }

  return lines.join('\n');
}

function formatYamlValue(value: unknown): string {
  if (typeof value === 'string') {
    if (value.includes('\n') || value.includes(': ') || value.length > 80) {
      return `|-\n            ${value.replace(/\n/g, '\n            ')}`;
    }
    if (/^\d/.test(value) || ['true','false','yes','no','on','off','null'].includes(value.toLowerCase())) {
      return `"${value}"`;
    }
    return value;
  }
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (value === null || value === undefined) return 'null';
  if (Array.isArray(value)) return JSON.stringify(value);
  return JSON.stringify(value);
}

export function stepsFromYaml(yaml: string): VisualStep[] {
  const steps: VisualStep[] = [];
  const lines = yaml.split('\n');
  let i = 0;
  let stepId = 0;

  while (i < lines.length) {
    const line = lines[i].trim();
    
    // Detect triggers
    const triggerMatch = line.match(/^(manual|scheduled|webhook|file_change|pipeline_complete):/);
    if (triggerMatch) {
      const triggerId = triggerMatch[1].replace('_', '-');
      steps.push({
        id: `step-${++stepId}`,
        componentId: triggerId,
        label: '',
        config: {},
        subTypes: [],
      });
    }

    // Detect action steps
    const actionMatch = line.match(/action:\s*(.*)/);
    if (actionMatch) {
      stepId++;
      const actionRef = actionMatch[1].trim();
      const componentId = Object.entries({
        'squidcloud/echo': 'echo',
        'squidcloud/transform': 'transform',
        'squidcloud/http': 'http-request',
        'squidcloud/webhook': 'webhook-send',
        'squidcloud/file-copy': 'file-copy',
        'squidcloud/file-move': 'file-move',
        'squidcloud/file-delete': 'file-delete',
        'squidcloud/file-upload': 'file-upload',
        'squidcloud/file-download': 'file-download',
        'squidcloud/compress': 'file-compress',
        'squidcloud/extract': 'file-extract',
        'squidcloud/sync': 'file-sync',
        'squidcloud/scan': 'file-scan',
        'squidcloud/slack': 'slack-message',
        'squidcloud/discord': 'discord-message',
        'squidcloud/email': 'email-send',
        'squidcloud/condition': 'condition',
        'squidcloud/for-each': 'for-loop',
        'squidcloud/delay': 'delay',
        'squidcloud/try-catch': 'try-catch',
        'squidcloud/template': 'template',
        'squidcloud/log': 'log-message',
        'squidcloud/push': 'push-notification',
        'squidcloud/script': 'custom-script',
      }).find(([ref]) => actionRef === ref)?.[1] || actionRef.replace('squidcloud/', '');

      const nameMatch = lines.slice(Math.max(0, i-2), i).find(l => l.trim().startsWith('name:'));
      const label = nameMatch ? nameMatch.replace(/.*name:\s*"?(.*?)"?\s*$/, '$1') : '';

      steps.push({
        id: `step-${stepId}`,
        componentId,
        label,
        config: {},
        subTypes: [],
      });
    }

    i++;
  }

  return steps;
}
